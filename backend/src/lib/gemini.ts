import { env } from '../config/env.js';
import { logger } from './logger.js';

/**
 * One call to Gemini, and every way it can fail collapsed into `null`.
 *
 * Extracted when a second caller appeared (free-text booking, milestone 3.2) and
 * the alternative was a second copy of the same fetch, the same abort, the same
 * `!response.ok` branch and the same candidate-extraction path. Two copies means
 * a quota bug gets fixed in one of them.
 *
 * **Null is an ordinary outcome, not an error.** No key configured, a timeout, a
 * quota refusal, a malformed body — the caller's answer is always the same: do
 * the thing that does not need a model. That rule is SPEC §11.3 for the briefing
 * and it is why free-text booking can fall back to the menu without a special
 * case. Nothing here throws, so no caller has to wrap it.
 *
 * What this deliberately does NOT do is decide whether the answer is any good.
 * Both callers check the model's output against something they already know to be
 * true — the briefing compares its figures, the parser matches names against the
 * database — and that check belongs with the caller who knows what correct means.
 */

const ENDPOINT = 'https://generativelanguage.googleapis.com/v1beta/models';

export interface GenerateRequest {
  /** The static system instruction — the job, and the rules for doing it. */
  instruction: string;
  /** The turn's own content. */
  input: string;
  temperature: number;
  maxOutputTokens: number;
  /**
   * How long the caller is willing to wait.
   *
   * Per-caller rather than a constant, because the two callers have completely
   * different deadlines: a briefing is generated by a cron job at 7am and can
   * afford seconds, while a customer sitting in WhatsApp cannot. Whoever is
   * waiting decides.
   */
  timeoutMs: number;
  /** Named in the log line, so a misconfiguration says which feature is degraded. */
  purpose: string;
}

export async function generate(request: GenerateRequest): Promise<string | null> {
  const key = env.GEMINI_API_KEY;
  if (!key) return null;

  try {
    const response = await fetch(
      `${ENDPOINT}/${env.GEMINI_MODEL}:generateContent?key=${encodeURIComponent(key)}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          systemInstruction: { parts: [{ text: request.instruction }] },
          contents: [{ role: 'user', parts: [{ text: request.input }] }],
          generationConfig: {
            temperature: request.temperature,
            maxOutputTokens: request.maxOutputTokens,
          },
        }),
        signal: AbortSignal.timeout(request.timeoutMs),
      },
    );

    if (!response.ok) {
      // Worth seeing once, at warn: the feature still works, but somebody
      // configured something that is not doing anything.
      logger.warn({ status: response.status, purpose: request.purpose }, 'gemini declined');
      return null;
    }

    const data = (await response.json()) as {
      candidates?: { content?: { parts?: { text?: string }[] } }[];
    };

    const text =
      data.candidates?.[0]?.content?.parts?.map((part) => part.text ?? '').join('') ?? '';
    return text.trim() || null;
  } catch (err) {
    // Includes the timeout, which is the common one.
    logger.warn({ err, purpose: request.purpose }, 'gemini unavailable');
    return null;
  }
}
